class TestCvGeneratorJob < CvGeneratorJob
  # Override OpenAI call to use mock data
  def call_azure_openai_api
    MOCK_GENERATED_DATA
  end

  # Override to inject mock data directly
  def generate_pdf_for_resume
    Rails.logger.info "=== GENERATING PDF FOR RESUME WITH PRAWN ==="
    begin
      resume = @resume_id ? Resume.find(@resume_id).reload : @cv_generation.resume.reload

      # Use our mock data directly instead of looking in metadata
      generated_data = MOCK_GENERATED_DATA.transform_keys(&:to_sym)
      generated_data = generated_data.deep_transform_keys(&:to_sym)

      puts "Generating PDF with data:"
      puts "- Professional Summary: #{generated_data[:professional_summary].truncate(100)}"
      puts "- Work Experiences: #{generated_data[:work_experiences].size} entries"
      puts "- Skills: #{generated_data[:skills].size} categories"
      puts "- Education: #{generated_data[:educations].size} entries"
      puts "- Certifications: #{generated_data[:certifications].size} entries"
      puts "- Languages: #{generated_data[:languages].size} entries"

      pdf = generate_prawn_pdf(resume, generated_data)

      # Write PDF directly to file
      filename = "test_format_pdf.pdf"
      File.write(filename, pdf)
      puts "PDF size: #{pdf.bytesize} bytes"

      # Store in metadata for consistency - include version info for caching
      @cv_generation.update!(
        metadata: @cv_generation.metadata.merge({
          pdf_generated: true,
          pdf_filename: filename,
          pdf_size: pdf.bytesize,
          pdf_data: Base64.encode64(pdf),
          pdf_version: PDF_VERSION,
          pdf_generated_at: Time.now.to_i,
          pdf_cache_key: "test_#{PDF_VERSION}_#{Time.now.to_i}"
        })
      )
      Rails.logger.info "PDF data stored in database (Base64 encoded)"
    rescue => e
      Rails.logger.error "PDF generation failed: #{e.message}"
      Rails.logger.error e.backtrace.join("\n")
      @cv_generation.update!(metadata: @cv_generation.metadata.merge({
        pdf_generated: false,
        pdf_error: e.message
      }))
      raise e
    end
  end
end

